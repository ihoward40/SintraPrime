import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import process from "node:process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function mkdirp(p) {
  fs.mkdirSync(p, { recursive: true });
}

function writeText(p, content) {
  mkdirp(path.dirname(p));
  fs.writeFileSync(p, content, "utf8");
}

function sha256(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}

function sha256File(p) {
  if (!fs.existsSync(p)) return "FILE_NOT_FOUND";
  return sha256(fs.readFileSync(p));
}

function now() {
  return new Date().toISOString();
}

function usage() {
  process.stderr.write(
    "Usage: node scripts/case/generate-case-packet.mjs <CASE_ID> [--out <dir>]\n" +
    "\nExample:\n  node scripts/case/generate-case-packet.mjs CASE-666234B709\n"
  );
  process.exit(2);
}

function readJson(p) {
  if (!fs.existsSync(p)) return null;
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch {
    return null;
  }
}

function readFile(p) {
  if (!fs.existsSync(p)) return null;
  return fs.readFileSync(p, "utf8");
}

function collectSectionItems(caseDir, sectionDir) {
  const dir = path.join(caseDir, sectionDir);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f !== "README.md" && f.endsWith(".md"))
    .sort()
    .map((f) => path.join(sectionDir, f));
}

