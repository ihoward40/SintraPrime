function buildTimeline(manifest, custodyLog) {
  const entries = [];
  if (custodyLog) {
    for (const line of custodyLog.split(/\r?\n/).filter(Boolean)) {
      try {
        const entry = JSON.parse(line);
        entries.push(entry);
      } catch {
        // skip malformed
      }
    }
  }

  const rows = entries
    .map((e) => `| ${e.timestamp ?? ""} | ${e.event_type ?? ""} | ${e.evidence_id ?? "—"} | ${e.description?.slice(0, 80) ?? ""}… |`)
    .join("\n");

  return `# Timeline

**Case ID:** ${manifest?.case_id ?? "UNKNOWN"}  
**Generated:** ${now()}

---

## Case Event Chronology

| Timestamp | Event Type | Evidence ID | Description |
|-----------|------------|-------------|-------------|
${rows || "| — | No events recorded | — | — |"}

---

## Key Milestones

| Milestone | Status |
|-----------|--------|
| Repository initialized | ✅ Complete |
| Deficiency notice imported | ✅ Complete |
| Hash verification | ⚠️ Pending — human custodian action required |
| Evidence review | ⚠️ Pending |
| Readiness score ≥ 70 | ⚠️ Pending — score currently ${manifest ? "see readiness document" : "unknown"} |
| External action approval | 🔒 Locked |
| Response submitted | 🔒 Locked |
`;
}

