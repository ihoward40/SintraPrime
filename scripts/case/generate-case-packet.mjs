// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  const argv = process.argv.slice(2);
  if (argv.includes("--help") || argv.includes("-h")) {
    process.stdout.write(
      "Usage: node scripts/case/generate-case-packet.mjs <CASE_ID> [--out <dir>]\n"
    );
    process.exit(0);
  }

  const caseId = argv[0] && !argv[0].startsWith("-") ? argv[0].trim() : "";
  if (!caseId) usage();

  const getFlag = (name) => {
    const idx = argv.findIndex((a) => a === name);
    if (idx === -1) return null;
    const v = String(argv[idx + 1] ?? "").trim();
    return v || null;
  };

  const caseDir = path.join(REPO_ROOT, "cases", caseId);
  if (!fs.existsSync(caseDir)) {
    process.stderr.write(`Error: Case directory not found: ${caseDir}\n`);
    process.exit(1);
  }

  const outRoot =
    getFlag("--out") ||
    path.join(REPO_ROOT, "exports", "case_packets", caseId);

  const generatedAt = now();
  const packetId = `${caseId}-PKT-${generatedAt.replace(/[:.]/g, "-")}`;

  // Load source data
  const manifest = readJson(path.join(caseDir, "EVIDENCE-MANIFEST.json"));
  const readiness = readJson(path.join(caseDir, "LITIGATION-READINESS-SCORE.json"));
  const custodyLog = readFile(path.join(caseDir, "audit", "CHAIN-OF-CUSTODY.jsonl"));

  if (!manifest) {
    process.stderr.write(`Error: EVIDENCE-MANIFEST.json not found in ${caseDir}\n`);
    process.exit(1);
  }

  mkdirp(outRoot);

  // Generate all sections
  const sections = {
    "00_COVER_SHEET.md": buildCoverSheet(manifest, readiness, generatedAt, packetId),
    "01_CASE_SUMMARY.md": buildCaseSummary(manifest, readiness),
    "02_TIMELINE.md": buildTimeline(manifest, custodyLog),
    "03_EVIDENCE_INDEX.md": buildEvidenceIndex(manifest),
    "04_DEFICIENCY_NOTICE.md": buildDeficiencyNoticeSection(caseDir),
    "05_SUPPORTING_EXHIBITS.md": buildSupportingExhibits(manifest, caseDir),
    "06_AUTHORITY_INDEX.md": buildAuthorityIndex(caseDir),
    "07_OUTSTANDING_REQUESTS.md": buildOutstandingRequests(readiness),
    "08_NEXT_DEADLINES.md": buildNextDeadlines(caseDir),
  };

  for (const [filename, content] of Object.entries(sections)) {
    writeText(path.join(outRoot, filename), content);
  }

  // Audit receipt requires a hash of the packet directory
  const packetHash = sha256(
    Buffer.from(
      Object.entries(sections)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([, c]) => c)
        .join("\n")
    )
  );
  writeText(
    path.join(outRoot, "09_AUDIT_RECEIPT.md"),
    buildAuditReceipt(manifest, custodyLog, readiness, packetHash)
  );

  // Packet index
  const indexLines = Object.keys(sections)
    .concat(["09_AUDIT_RECEIPT.md"])
    .sort()
    .map((f) => `- [${f}](./${f}) — SHA-256: ${sha256File(path.join(outRoot, f))}`)
    .join("\n");

  writeText(
    path.join(outRoot, "00_PACKET_INDEX.md"),
    `# Case Packet Index\n\n**Packet ID:** ${packetId}  \n**Generated:** ${generatedAt}  \n**Case ID:** ${caseId}  \n**Governance:** External actions LOCKED — review only\n\n## Sections\n\n${indexLines}\n\n---\n\n*Generated by SintraPrime Governance Engine — no external transmission occurred.*\n`
  );

  const result = {
    kind: "CasePacket",
    packet_id: packetId,
    case_id: caseId,
    generated_at: generatedAt,
    out_dir: outRoot,
    packet_sha256: packetHash,
    sections: Object.keys(sections).concat(["09_AUDIT_RECEIPT.md"]).sort(),
    governance: {
      external_actions_locked: true,
      purpose: "REVIEW ONLY — no external transmission",
    },
  };

  process.stdout.write(JSON.stringify(result, null, 2) + "\n");
}

main().catch((err) => {
  process.exitCode = 1;
  process.stderr.write(String(err?.stack || err?.message || err) + "\n");
});
